import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const collection = require('@iconify-json/lucide/icons.json');
const names = [
  'package',
  'layout-dashboard',
  'package-plus',
  'clock-3',
  'triangle-alert',
  'users',
  'truck',
  'history',
  'user-round',
  'search',
  'refresh-cw',
  'plus',
  'arrow-right',
  'arrow-left',
  'log-out',
  'menu',
  'x',
  'check',
  'check-check',
  'scan-line',
  'shield-check',
  'lock-keyhole',
  'phone',
  'pencil',
  'trash-2',
  'key-round',
  'chevron-right',
  'inbox',
  'send',
  'map-pin',
  'circle-check',
  'loader-circle',
  'ban',
  'box',
  'move-up-right',
  'eye',
  'eye-off',
];
const icons = Object.fromEntries(
  names.map((name) => {
    const icon = collection.icons[name] || collection.icons[collection.aliases?.[name]?.parent];
    if (!icon) throw new Error(`Unknown Lucide icon: ${name}`);
    return [name, { width: collection.width, height: collection.height, ...icon }];
  })
);
const target = fileURLToPath(new URL('../src/assets/icons.ts', import.meta.url));
writeFileSync(
  target,
  `// Generated by scripts/generate-icons.mjs. Lucide icons (ISC license).\n// Only these icons are bundled; no runtime network requests.\nexport const icons = ${JSON.stringify(icons, null, 2)} as const\n`
);
console.log(`Generated ${names.length} local Iconify icons`);
